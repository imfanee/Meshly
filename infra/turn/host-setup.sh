#!/usr/bin/env bash
# Meshly TURN: Proxmox host setup, in separately approved stages.
#
# Usage (as root on the Proxmox host, with /root/meshly/host.env present):
#   bash host-setup.sh preflight   # read-only checks of host.env against the host
#   bash host-setup.sh network     # backup, arm 5-minute auto-rollback, add private bridge
#   bash host-setup.sh disarm      # cancel the auto-rollback (after a NEW ssh session works)
#   bash host-setup.sh nat         # install and start the NAT/firewall service
#   bash host-setup.sh container   # download template, create and start the LXC container
#   bash host-setup.sh status      # show what is in place
#   bash host-setup.sh uninstall   # remove NAT service and bridge stanza (container left alone)
#
# Never touches existing guests, vmbr0 or the public IP configuration.

set -euo pipefail

BASE=/root/meshly
ENV_FILE="$BASE/host.env"
BACKUP_DIR="$BASE/backup"
TS="$(date +%Y%m%d-%H%M%S)"

die() { echo "ERROR: $*" >&2; exit 1; }
info() { echo "==> $*"; }

[ "$(id -u)" -eq 0 ] || die "run as root"
[ -f "$ENV_FILE" ] || die "missing $ENV_FILE (copy from host.env.example and fill in)"
# shellcheck source=/dev/null
. "$ENV_FILE"

for v in CTID CT_HOSTNAME STORAGE TEMPLATE_STORAGE TEMPLATE ROOTFS_GB MEMORY_MB SWAP_MB CORES \
         BRIDGE BRIDGE_IP PREFIX SUBNET CT_IP PUBLIC_IF PUBLIC_IP RELAY_MIN RELAY_MAX TLS_PUBLIC_PORT FORWARD_HTTP_80; do
    [ -n "${!v:-}" ] || die "$v is not set in $ENV_FILE"
done

[ "$BRIDGE" != "$PUBLIC_IF" ] || die "BRIDGE must not be the public interface"
[ "$BRIDGE" != "vmbr0" ] || die "refusing to modify vmbr0"

preflight() {
    info "Preflight (read-only)"
    command -v pct >/dev/null || die "pct not found: not a Proxmox host?"
    ip -br addr show "$PUBLIC_IF" | grep -q "$PUBLIC_IP" || die "PUBLIC_IP $PUBLIC_IP not found on $PUBLIC_IF"
    if pct status "$CTID" >/dev/null 2>&1 || qm status "$CTID" >/dev/null 2>&1; then
        die "guest ID $CTID already exists"
    fi
    if ip -4 addr | grep -v " $BRIDGE" | grep -q "inet ${SUBNET%.*}\."; then
        die "subnet $SUBNET appears to be in use already"
    fi
    if ip link show "$BRIDGE" >/dev/null 2>&1; then
        echo "note: $BRIDGE already exists; it will be reused if its address is $BRIDGE_IP/$PREFIX"
        ip -br addr show "$BRIDGE"
    fi
    pvesm status | awk 'NR>1 {print $1}' | grep -qx "$STORAGE" || die "storage $STORAGE not found"
    for spec in "udp 3478" "tcp 3478" "tcp $TLS_PUBLIC_PORT"; do
        set -- $spec
        if ss -H -l -n "--$1" | awk '{print $5}' | grep -Eq "[:.]$2$"; then
            die "host already listens on $1/$2; choose another port or stop that service"
        fi
    done
    if [ "$FORWARD_HTTP_80" = "yes" ] && ss -H -ltn | awk '{print $5}' | grep -Eq '[:.]80$'; then
        die "host listens on tcp/80; set FORWARD_HTTP_80=no and use DNS-01 for the certificate"
    fi
    info "Preflight passed"
}

arm_rollback() {
    mkdir -p "$BACKUP_DIR"
    cp -a /etc/network/interfaces "$BACKUP_DIR/interfaces.$TS"
    cat > "$BASE/rollback.sh" <<EOF
#!/bin/bash
# Auto-generated by host-setup.sh on $TS: restore network config if not disarmed.
cp -a "$BACKUP_DIR/interfaces.$TS" /etc/network/interfaces
ifreload -a || systemctl restart networking
logger "meshly: network rollback executed (backup $TS)"
EOF
    chmod 700 "$BASE/rollback.sh"
    systemctl stop meshly-net-rollback.timer 2>/dev/null || true
    systemctl reset-failed meshly-net-rollback.service meshly-net-rollback.timer 2>/dev/null || true
    systemd-run --unit=meshly-net-rollback --on-active=300 /bin/bash "$BASE/rollback.sh" >/dev/null
    info "Auto-rollback armed: network config restores in 5 minutes unless you run 'host-setup.sh disarm'"
}

network() {
    preflight
    arm_rollback
    if grep -qE "^[[:space:]]*(auto|iface)[[:space:]]+$BRIDGE([[:space:]]|$)" /etc/network/interfaces; then
        info "$BRIDGE stanza already present in /etc/network/interfaces"
    else
        info "Adding $BRIDGE ($BRIDGE_IP/$PREFIX) to /etc/network/interfaces"
        cat >> /etc/network/interfaces <<EOF

# Meshly TURN private bridge (added by infra/turn/host-setup.sh on $TS)
auto $BRIDGE
iface $BRIDGE inet static
	address $BRIDGE_IP/$PREFIX
	bridge-ports none
	bridge-stp off
	bridge-fd 0
EOF
    fi
    info "Bringing up $BRIDGE only (vmbr0 untouched)"
    ifup "$BRIDGE"
    ip -br addr show "$BRIDGE"
    echo
    echo "NEXT: open a NEW ssh session to this host. If it works, run: bash host-setup.sh disarm"
    echo "If you do nothing, the original /etc/network/interfaces is restored in 5 minutes."
}

disarm() {
    systemctl stop meshly-net-rollback.timer 2>/dev/null || true
    systemctl reset-failed meshly-net-rollback.service meshly-net-rollback.timer 2>/dev/null || true
    info "Auto-rollback disarmed"
}

nat() {
    info "Enabling IPv4 forwarding"
    echo "net.ipv4.ip_forward=1" > /etc/sysctl.d/99-meshly-turn.conf
    sysctl -q -p /etc/sysctl.d/99-meshly-turn.conf

    info "Installing NAT script and service"
    mkdir -p /etc/meshly
    install -m 600 "$ENV_FILE" /etc/meshly/turn-nat.env
    install -m 755 "$BASE/meshly-turn-nat.sh" /usr/local/sbin/meshly-turn-nat.sh
    install -m 644 "$BASE/meshly-turn-nat.service" /etc/systemd/system/meshly-turn-nat.service
    systemctl daemon-reload
    systemctl enable --now meshly-turn-nat.service
    /usr/local/sbin/meshly-turn-nat.sh show
}

container() {
    preflight
    ip link show "$BRIDGE" >/dev/null 2>&1 || die "$BRIDGE does not exist; run the network stage first"
    info "Ensuring template $TEMPLATE"
    pveam update >/dev/null
    if ! pveam list "$TEMPLATE_STORAGE" | grep -q "$TEMPLATE"; then
        pveam download "$TEMPLATE_STORAGE" "$TEMPLATE"
    fi
    info "Creating unprivileged container $CTID ($CT_HOSTNAME)"
    pct create "$CTID" "$TEMPLATE_STORAGE:vztmpl/$TEMPLATE" \
        --hostname "$CT_HOSTNAME" \
        --unprivileged 1 \
        --features nesting=1 \
        --onboot 1 \
        --cores "$CORES" \
        --memory "$MEMORY_MB" \
        --swap "$SWAP_MB" \
        --rootfs "$STORAGE:$ROOTFS_GB" \
        --net0 "name=eth0,bridge=$BRIDGE,ip=$CT_IP/$PREFIX,gw=$BRIDGE_IP" \
        --nameserver "1.1.1.1 9.9.9.9" \
        --description "Meshly coturn relay (managed by infra/turn in github.com/imfanee/Meshly)"
    pct start "$CTID"
    sleep 5
    pct exec "$CTID" -- bash -c 'getent hosts deb.debian.org >/dev/null && echo "container has DNS and internet" || echo "WARNING: container cannot resolve deb.debian.org"'
}

status() {
    echo "--- bridge"; ip -br addr show "$BRIDGE" 2>/dev/null || echo "$BRIDGE missing"
    echo "--- rollback timer"; systemctl is-active meshly-net-rollback.timer 2>/dev/null || echo "not armed"
    echo "--- nat service"; systemctl is-active meshly-turn-nat.service 2>/dev/null || echo "not installed"
    echo "--- container"; pct status "$CTID" 2>/dev/null || echo "container $CTID missing"
    [ -x /usr/local/sbin/meshly-turn-nat.sh ] && /usr/local/sbin/meshly-turn-nat.sh show || true
}

uninstall() {
    info "Removing NAT service (container $CTID is NOT touched)"
    systemctl disable --now meshly-turn-nat.service 2>/dev/null || true
    [ -x /usr/local/sbin/meshly-turn-nat.sh ] && /usr/local/sbin/meshly-turn-nat.sh remove || true
    rm -f /etc/systemd/system/meshly-turn-nat.service /usr/local/sbin/meshly-turn-nat.sh /etc/sysctl.d/99-meshly-turn.conf
    systemctl daemon-reload
    echo "To remove the bridge, delete the 'Meshly TURN private bridge' stanza from /etc/network/interfaces after stopping the container, then: ifdown $BRIDGE"
}

case "${1:-}" in
    preflight) preflight ;;
    network)   network ;;
    disarm)    disarm ;;
    nat)       nat ;;
    container) container ;;
    status)    status ;;
    uninstall) uninstall ;;
    *) sed -n '2,16p' "$0"; exit 1 ;;
esac
